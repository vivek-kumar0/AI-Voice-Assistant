"""
pdf_qa_engine.py
------------------
Main orchestrator for the "ask questions about a PDF" feature.

Pipeline:
    1. load_pdf()  -> extract text, split into chunks, build a TF-IDF index
    2. ask()       -> retrieve the most relevant chunks for the question,
                       then (if an AI engine/API key is available) ask the
                       LLM to compose a natural answer using ONLY that
                       retrieved context. Falls back to returning the raw
                       matched text if no AI engine is configured.

This keeps the feature fully usable offline (raw-passage mode) while
producing much more natural answers when an OpenAI key is present.
"""

from pdf_assistant.pdf_loader import PDFLoader, PDFLoadError
from pdf_assistant.text_chunker import chunk_text
from pdf_assistant.vector_store import TFIDFVectorStore
from utils.logger import get_logger

logger = get_logger(__name__)


class PDFQAEngine:
    """Loads a PDF and answers natural-language questions about its content."""

    def __init__(self, ai_engine=None):
        """
        Args:
            ai_engine: Optional AIEngine instance (assistant/ai_engine.py).
                If provided and configured with an API key, answers are
                generated by the LLM using retrieved passages as context.
                If None or unconfigured, raw matching passages are returned.
        """
        self.ai_engine = ai_engine
        self.vector_store = TFIDFVectorStore()
        self.loaded_filename = None
        self.is_loaded = False

    def load_pdf(self, file_path: str) -> str:
        """
        Load and index a PDF file so questions can be asked about it.

        Args:
            file_path (str): Path to the .pdf file selected by the user.

        Returns:
            str: A status message suitable for display/speech.
        """
        try:
            text = PDFLoader.extract_text(file_path)
        except PDFLoadError as e:
            logger.error(f"PDF load failed: {e}")
            self.is_loaded = False
            return f"I couldn't read that PDF: {e}"

        chunks = chunk_text(text)
        self.vector_store.build(chunks)

        self.loaded_filename = file_path.split("/")[-1].split("\\")[-1]
        self.is_loaded = True

        logger.info(f"PDF loaded and indexed: {self.loaded_filename}")
        return (
            f"I've loaded '{self.loaded_filename}' and split it into "
            f"{len(chunks)} sections. You can ask me questions about it now."
        )

    def ask(self, question: str, top_k: int = 4) -> str:
        """
        Answer a question using the currently loaded PDF.

        Args:
            question (str): The user's question about the PDF.
            top_k (int): How many relevant chunks to retrieve as context.

        Returns:
            str: The answer, or a message asking the user to load a PDF first.
        """
        if not self.is_loaded:
            return "Please upload a PDF first before asking questions about it."

        if not question or not question.strip():
            return "What would you like to know about the document?"

        try:
            matches = self.vector_store.search(question, top_k=top_k)
        except Exception as e:
            logger.error(f"PDF search failed: {e}")
            return "Something went wrong while searching the document."

        # Filter out very low-relevance matches (TF-IDF cosine similarity ~0
        # means the question likely isn't covered by the document at all).
        relevant_matches = [chunk for chunk, score in matches if score > 0.05]

        if not relevant_matches:
            return (
                "I couldn't find anything in the document that answers that. "
                "Could you rephrase the question?"
            )

        context = "\n\n---\n\n".join(relevant_matches)

        # If an AI engine with a working API key is available, ask it to
        # compose a proper answer grounded in the retrieved passages.
        if self.ai_engine and getattr(self.ai_engine, "client", None):
            return self.ai_engine.answer_with_context(question, context)

        # Offline fallback: return the raw best-matching passage(s).
        return (
            "Here's the most relevant passage I found in the document "
            f"(add an OpenAI API key for a summarized answer instead):\n\n"
            f"{relevant_matches[0][:600]}"
        )

    def reset(self):
        """Clear the currently loaded PDF and index."""
        self.vector_store = TFIDFVectorStore()
        self.loaded_filename = None
        self.is_loaded = False
        logger.info("PDF index cleared.")
